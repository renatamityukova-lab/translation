"""Промпты для LLM: системный промпт и пользовательский запрос.

Правила из постановки задачи (snake_case, единственное число, без предлогов,
терминология учётных систем) передаются модели через промпт.
"""

from __future__ import annotations

SYSTEM_PROMPT = (
    "Ты — полезный ассистент, профессиональный переводчик терминов учетных систем. "
    "Отвечай кратко и по существу."
)

_USER_PROMPT_TEMPLATE = """Переведи идентификатор 1С на английский язык.

Идентификатор: {identifier}

Требования к ответу:
- формат lower_snake_case: слова через «_», только строчные латинские буквы, цифры и «_»;
- переводи ВСЕ смысловые компоненты идентификатора, ничего не опускай и не обобщай;
- каждое слово — в единственном числе;
- предлоги и союзы не включать;
- используй общепринятые термины учётных систем (например, Контрагент → partner, Договор → contract,
  Покупатель → customer, Склад → warehouse);
- вернуть только результат перевода: без пояснений, кавычек и markdown.

Примеры:
ДоговорыКонтрагентов → partner_contract
ЗаказыПокупателей → customer_order
ТоварыНаСкладе → warehouse_stock"""


def build_user_prompt(identifier: str) -> str:
    """Сформировать пользовательский запрос для перевода идентификатора.

    :param identifier: идентификатор в стиле 1С, например ``ДоговорыКонтрагентов``
    """
    return _USER_PROMPT_TEMPLATE.format(identifier=identifier.strip())
